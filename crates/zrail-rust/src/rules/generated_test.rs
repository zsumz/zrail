//! Provenance manifests reject edited, smuggled, and nonportable generated source.

use std::{fs, path::PathBuf};

use zrail_core::GeneratedSourceContract;

use crate::inventory::{RepositoryEntry, RepositoryEntryKind};

use super::{digest, inspect_tree, manifest};

const SCHEMA: &str = "message Message {}\n";

#[test]
fn exact_generated_tree_passes() {
    let root = fixture_root("valid");
    reset(&root);
    let source = "//! @generated by fixture\npub struct Message;\n";
    fs::write(root.join("generated/message.rs"), source).expect("write source");
    fs::write(
        root.join("generated/MANIFEST.json"),
        manifest(&[("message.rs", source)]),
    )
    .expect("write manifest");

    let findings = inspect_tree(&root, &entries(&root, &["message.rs"]), &contract());

    assert!(findings.is_empty(), "{findings:?}");
    fs::remove_dir_all(root).expect("remove fixture");
}

#[test]
fn edited_and_smuggled_generated_source_fails() {
    let root = fixture_root("tampered");
    reset(&root);
    let original = "//! @generated by fixture\npub struct Message;\n";
    fs::write(
        root.join("generated/message.rs"),
        "//! @generated by fixture\npub struct Edited;\n",
    )
    .expect("write edited source");
    fs::write(
        root.join("generated/smuggled.rs"),
        "//! @generated by fixture\npub struct Smuggled;\n",
    )
    .expect("write smuggled source");
    fs::write(
        root.join("generated/MANIFEST.json"),
        manifest(&[("message.rs", original)]),
    )
    .expect("write manifest");

    let findings = inspect_tree(
        &root,
        &entries(&root, &["message.rs", "smuggled.rs"]),
        &contract(),
    );

    assert!(findings.iter().any(|finding| finding.id == "GEN-002"));
    assert!(findings.iter().any(|finding| finding.id == "GEN-003"));
    fs::remove_dir_all(root).expect("remove fixture");
}

#[test]
fn case_variant_source_extensions_cannot_escape_the_manifest() {
    let root = fixture_root("case-variant");
    reset(&root);
    let source = "//! @generated by fixture\npub struct Message;\n";
    fs::write(root.join("generated/message.RS"), source).expect("write source");
    fs::write(root.join("generated/MANIFEST.json"), manifest(&[])).expect("write manifest");

    let findings = inspect_tree(&root, &entries(&root, &["message.RS"]), &contract());

    assert!(findings.iter().any(|finding| finding.id == "GEN-003"));
    fs::remove_dir_all(root).expect("remove fixture");
}

#[test]
fn manifest_paths_are_normalized_and_source_only() {
    assert!(manifest::file_path("generated", "../escape.rs").is_err());
    assert!(manifest::file_path("generated", "nested\\escape.rs").is_err());
    assert!(manifest::file_path("generated", "artifact.bin").is_err());
    assert_eq!(
        manifest::file_path("generated", "nested/message.rs").as_deref(),
        Ok("generated/nested/message.rs")
    );
}

